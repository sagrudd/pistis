/// Monas-owned durable issuance and atomic single-use consumption boundary.
///
/// `record_verified` and `consume_exact` must be transactional durable
/// operations.  `consume_exact` must compare every field in
/// [`SiteTrustFactConsumptionRequestV1`], record the consumption/audit event,
/// and transition the fact to consumed in the same rollback-capable transaction.
/// It must not offer a read-then-consume compatibility sequence.
pub trait SiteTrustFactStoreV1 {
    /// Records one fact only after an Apple verifier returned a verified result.
    ///
    /// # Errors
    ///
    /// Duplicate ceremony IDs, unavailable durable state, or audit failures
    /// return a coarse error and must leave no partially issued fact.
    fn record_verified(
        &mut self,
        fact: SiteTrustHumanAuthorityFactV1,
    ) -> Result<(), SiteTrustFactConsumptionErrorV1>;

    /// Atomically compares and consumes one fact for the next Site Trust gate.
    ///
    /// # Errors
    ///
    /// A mismatch, replay, unavailable store, or audit failure must deny the
    /// gate without an authority fallback or a second consumption attempt.
    fn consume_exact(
        &mut self,
        request: SiteTrustFactConsumptionRequestV1,
    ) -> Result<SiteTrustFactConsumptionV1, SiteTrustFactConsumptionErrorV1>;
}

/// Failure while issuing a verified durable human-authority fact.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum SiteTrustFactIssuanceErrorV1 {
    /// The request did not bind one non-zero ceremony and exact payload intent.
    InvalidBinding,
    /// Apple App Attest was unavailable, invalid, or bound to another device/key.
    Attestation(AttestationVerificationFailureV1),
    /// The Monas-owned durable fact transaction rejected issuance.
    Store(SiteTrustFactConsumptionErrorV1),
}

impl fmt::Display for SiteTrustFactIssuanceErrorV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidBinding => formatter.write_str("Site Trust fact binding is invalid"),
            Self::Attestation(error) => write!(formatter, "Site Trust attestation failed: {error}"),
            Self::Store(error) => write!(formatter, "Site Trust fact store failed: {error}"),
        }
    }
}

impl std::error::Error for SiteTrustFactIssuanceErrorV1 {}

/// Verifies an iPhone assertion and durably records a fact without retaining raw assertion bytes.
///
/// # Errors
///
/// A failed request validation or unavailable/invalid Apple verifier returns
/// before the store is touched.  A successful verifier result is still denied
/// if the exact device and key do not match the request.
pub fn issue_site_trust_human_authority_fact_v1(
    attestation_verifier: &impl AppleAppAttestVerifierV1,
    store: &mut impl SiteTrustFactStoreV1,
    request: SiteTrustAttestationRequestV1,
    assertion: &AppleAppAttestAssertionV1,
) -> Result<SiteTrustHumanAuthorityFactV1, SiteTrustFactIssuanceErrorV1> {
    request.validate()?;
    let verification_request = request.verification_request();
    let verified_result = attestation_verifier
        .verify(&verification_request, assertion)
        .map_err(SiteTrustFactIssuanceErrorV1::Attestation)?;
    if verified_result.device_id != request.device_id || verified_result.key_id != request.key_id {
        return Err(SiteTrustFactIssuanceErrorV1::Attestation(
            AttestationVerificationFailureV1::BindingMismatch,
        ));
    }
    issue_site_trust_human_authority_fact_from_verified_v1(store, request, verified_result)
}

