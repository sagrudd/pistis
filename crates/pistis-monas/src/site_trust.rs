    impl SiteTrustFactStoreV1 for RecordingStore {
        fn record_verified(
            &mut self,
            fact: SiteTrustHumanAuthorityFactV1,
        ) -> Result<(), SiteTrustFactConsumptionErrorV1> {
            if self.fact.is_some() {
                return Err(SiteTrustFactConsumptionErrorV1::Replayed);
            }
            self.fact = Some(fact);
            Ok(())
        }

        fn consume_exact(
            &mut self,
            request: SiteTrustFactConsumptionRequestV1,
        ) -> Result<SiteTrustFactConsumptionV1, SiteTrustFactConsumptionErrorV1> {
            let Some(fact) = &self.fact else {
                return Err(SiteTrustFactConsumptionErrorV1::Unavailable);
            };
            if self.consumed {
                return Err(SiteTrustFactConsumptionErrorV1::Replayed);
            }
            if request != fact.consumption_request() {
                return Err(SiteTrustFactConsumptionErrorV1::BindingMismatch);
            }
            self.consumed = true;
            Ok(SiteTrustFactConsumptionV1 { id: fact.id() })
        }
    }

