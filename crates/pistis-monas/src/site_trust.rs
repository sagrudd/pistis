//! Fail-closed iPhone-attested Site Trust human-authority facts.
//!
//! This is a framework-neutral Pistis-to-Monas contract.  It binds an
//! iPhone-attestation verification request to the exact non-secret Proxenos
//! canonical payload and opaque Pistis intent.  It deliberately does not
//! provide an Apple verifier, HTTP route, browser session, local account, or
//! persistence implementation.  Monas owns the durable transaction through
//! [`SiteTrustFactStoreV1`].

