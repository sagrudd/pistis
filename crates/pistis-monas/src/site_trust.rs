/// Structural failure when parsing a Proxenos canonical Site Trust payload.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum SiteTrustCanonicalPayloadErrorV1 {
    /// The payload is truncated, oversized, reordered, or contains extra data.
    NonCanonical,
    /// A payload value is not printable ASCII or has an invalid length.
    InvalidField,
    /// The exact Proxenos profile or v1 version is absent.
    WrongProfile,
    /// The payload is not a pending ceremony request.
    WrongState,
    /// The audience or purpose is outside the closed Proxenos v1 set.
    UnsupportedAudienceOrPurpose,
    /// The payload attempts to carry authority material that cannot cross this boundary.
    ProhibitedMaterial,
    /// The opaque intent reference is malformed.
    InvalidIntentReference,
}

impl fmt::Display for SiteTrustCanonicalPayloadErrorV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::NonCanonical => "Site Trust canonical payload is invalid",
            Self::InvalidField => "Site Trust canonical payload field is invalid",
            Self::WrongProfile => "Site Trust canonical payload profile is invalid",
            Self::WrongState => "Site Trust canonical payload state is invalid",
            Self::UnsupportedAudienceOrPurpose => "Site Trust audience or purpose is unsupported",
            Self::ProhibitedMaterial => "Site Trust payload crosses prohibited material",
            Self::InvalidIntentReference => "Site Trust intent reference is invalid",
        })
    }
}

impl std::error::Error for SiteTrustCanonicalPayloadErrorV1 {}

/// Exact parsed non-secret Proxenos Site Trust payload bytes.
///
/// Proxenos remains the final authority that validates the complete payload
/// against its active Site Trust state.  This type only accepts the frozen v1
/// canonical grammar so Pistis can bind the exact bytes to human intent.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SiteTrustCanonicalPayloadV1 {
    canonical_bytes: Vec<u8>,
    digest: [u8; 32],
    site_id: String,
    audience: String,
    purpose: String,
    intent_reference: String,
}

impl SiteTrustCanonicalPayloadV1 {
    /// Parses exactly one frozen 13-field Proxenos v1 TLV payload.
    ///
    /// # Errors
    ///
    /// Returns a redacted structural failure without retaining raw input in
    /// the error.  It never validates a detached Site Trust proof.
    pub fn parse(canonical_bytes: Vec<u8>) -> Result<Self, SiteTrustCanonicalPayloadErrorV1> {
        let values = parse_payload_fields(&canonical_bytes)?;
        if values[0] != PROXENOS_PAYLOAD_PROFILE_V1 || values[1] != "1" {
            return Err(SiteTrustCanonicalPayloadErrorV1::WrongProfile);
        }
        if values[2] != "request-pending" {
            return Err(SiteTrustCanonicalPayloadErrorV1::WrongState);
        }
        if !matches!(
            values[7].as_str(),
            "monas-local"
                | "oikodome-local"
                | "dasobjectstore-local"
                | "phoreus-registry-local"
                | "phoreus-forge-local"
                | "jenkins-local"
        ) || !matches!(
            values[8].as_str(),
            "trust-observe" | "trust-admission" | "trust-deploy" | "trust-execute"
        ) {
            return Err(SiteTrustCanonicalPayloadErrorV1::UnsupportedAudienceOrPurpose);
        }
        if values
            .iter()
            .any(|value| contains_prohibited_material(value))
        {
            return Err(SiteTrustCanonicalPayloadErrorV1::ProhibitedMaterial);
        }
        if !valid_intent_reference(&values[12]) {
            return Err(SiteTrustCanonicalPayloadErrorV1::InvalidIntentReference);
        }
        Ok(Self {
            digest: Sha256::digest(&canonical_bytes).into(),
            canonical_bytes,
            site_id: values[3].clone(),
            audience: values[7].clone(),
            purpose: values[8].clone(),
            intent_reference: values[12].clone(),
        })
    }

    /// Returns the exact bytes which must be forwarded unchanged to Proxenos.
    #[must_use]
    pub fn canonical_bytes(&self) -> &[u8] {
        &self.canonical_bytes
    }

    /// Returns the SHA-256 digest of the exact canonical bytes.
    #[must_use]
    pub const fn digest(&self) -> &[u8; 32] {
        &self.digest
    }

    /// Returns the canonical payload's non-secret Site Trust identifier.
    #[must_use]
    pub fn site_id(&self) -> &str {
        &self.site_id
    }

    /// Returns the exact closed product audience.
    #[must_use]
    pub fn audience(&self) -> &str {
        &self.audience
    }

    /// Returns the exact closed Site Trust purpose.
    #[must_use]
    pub fn purpose(&self) -> &str {
        &self.purpose
    }

    /// Returns the opaque field-13 Pistis intent evidence reference.
    #[must_use]
    pub fn intent_reference(&self) -> &str {
        &self.intent_reference
    }
}

/// A bounded raw App Attest assertion accepted only as untrusted verifier input.
///
/// This value is never stored in a human-authority fact, returned to Monas, or
/// emitted in an error.  It is retained only for the synchronous verifier call.
#[derive(Clone, Eq, PartialEq)]
pub struct AppleAppAttestAssertionV1(Vec<u8>);

impl fmt::Debug for AppleAppAttestAssertionV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("AppleAppAttestAssertionV1")
            .field("byte_len", &self.0.len())
            .finish()
    }
}

impl AppleAppAttestAssertionV1 {
    /// Bounds untrusted assertion bytes before they reach an Apple verifier.
    ///
    /// # Errors
    ///
    /// Returns a redacted verification failure for empty or oversized input.
    pub fn parse(bytes: Vec<u8>) -> Result<Self, AttestationVerificationFailureV1> {
        if bytes.is_empty() || bytes.len() > MAXIMUM_ASSERTION_BYTES {
            return Err(AttestationVerificationFailureV1::Invalid);
        }
        Ok(Self(bytes))
    }

    /// Returns bounded assertion bytes only to sibling Pistis verification
    /// boundaries.  They must remain transient and must never be retained in a
    /// fact, vector, error, or transport response.
    #[must_use]
    pub(crate) fn transient_bytes(&self) -> &[u8] {
        &self.0
    }
}

/// A versioned opaque Pistis intent binding required by the Proxenos UDS profile.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SiteTrustPistisIntentV1(String);

impl SiteTrustPistisIntentV1 {
    /// Parses one exact `mnemosyne.pistis.intent.v1:` intent reference.
    ///
    /// # Errors
    ///
    /// Returns a redacted failure for an unknown, oversized, or non-canonical intent.
    pub fn parse(value: String) -> Result<Self, SiteTrustCanonicalPayloadErrorV1> {
        let Some(reference) = value.strip_prefix(PISTIS_INTENT_PREFIX_V1) else {
            return Err(SiteTrustCanonicalPayloadErrorV1::InvalidIntentReference);
        };
        if value.len() > MAXIMUM_INTENT_BYTES || !valid_intent_reference(reference) {
            return Err(SiteTrustCanonicalPayloadErrorV1::InvalidIntentReference);
        }
        Ok(Self(value))
    }

    /// Returns the exact wire value accepted by Proxenos.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }

    fn reference(&self) -> &str {
        self.0
            .strip_prefix(PISTIS_INTENT_PREFIX_V1)
            .expect("validated Site Trust intent prefix")
    }
}

/// The exact non-secret request that an Apple App Attest verifier must bind.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct SiteTrustAttestationRequestV1 {
    /// Installation owning this one-use ceremony.
    pub installation_id: InstallationId,
    /// Enrolled physical iPhone expected to attest.
    pub device_id: DeviceId,
    /// Exact registered iPhone verification key expected to attest.
    pub key_id: KeyId,
    /// Independently generated non-zero ceremony identifier.
    pub ceremony_id: SiteTrustFactCeremonyIdV1,
    /// Exact frozen Proxenos canonical Site Trust payload.
    pub canonical_payload: SiteTrustCanonicalPayloadV1,
    /// Exact opaque Pistis intent from the Proxenos UDS contract.
    pub pistis_intent: SiteTrustPistisIntentV1,
    /// Host-recorded issuance time for durable audit evidence.
    pub issued_at: UnixTimeMillis,
}

impl SiteTrustAttestationRequestV1 {
    /// Validates cross-field request bindings before any verifier or store call.
    ///
    /// # Errors
    ///
    /// Returns a redacted failure when the all-zero ceremony ID or intent/payload
    /// binding is invalid.
    pub fn validate(&self) -> Result<(), SiteTrustFactIssuanceErrorV1> {
        if self.ceremony_id.is_zero_sentinel()
            || self.pistis_intent.reference() != self.canonical_payload.intent_reference()
        {
            return Err(SiteTrustFactIssuanceErrorV1::InvalidBinding);
        }
        Ok(())
    }

    /// Produces the exact domain-separated digest that App Attest must verify.
    #[must_use]
    pub fn verification_request(&self) -> SiteTrustAttestationVerificationRequestV1 {
        let digest = digest_components(
            ATTESTATION_CHALLENGE_DOMAIN_V1,
            [
                self.installation_id.as_bytes().as_slice(),
                self.device_id.as_bytes().as_slice(),
                self.key_id.as_bytes().as_slice(),
                self.ceremony_id.as_bytes().as_slice(),
                self.canonical_payload.canonical_bytes(),
                self.pistis_intent.as_str().as_bytes(),
                &self.issued_at.get().to_be_bytes(),
            ],
        );
        SiteTrustAttestationVerificationRequestV1 {
            installation_id: self.installation_id,
            device_id: self.device_id,
            key_id: self.key_id,
            ceremony_id: self.ceremony_id,
            canonical_payload_digest: *self.canonical_payload.digest(),
            pistis_intent: self.pistis_intent.clone(),
            challenge_digest: SiteTrustAttestationChallengeDigestV1(digest),
        }
    }
}

