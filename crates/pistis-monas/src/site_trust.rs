fn parse_payload_fields(
    canonical_bytes: &[u8],
) -> Result<[String; FACT_PAYLOAD_FIELDS], SiteTrustCanonicalPayloadErrorV1> {
    let mut fields = Vec::with_capacity(FACT_PAYLOAD_FIELDS);
    let mut position = 0_usize;
    for expected_tag in 1..=u8::try_from(FACT_PAYLOAD_FIELDS).expect("fixed field count") {
        let Some(&tag) = canonical_bytes.get(position) else {
            return Err(SiteTrustCanonicalPayloadErrorV1::NonCanonical);
        };
        position += 1;
        if tag != expected_tag {
            return Err(SiteTrustCanonicalPayloadErrorV1::NonCanonical);
        }
        let Some(length_bytes) = canonical_bytes.get(position..position + 4) else {
            return Err(SiteTrustCanonicalPayloadErrorV1::NonCanonical);
        };
        position += 4;
        let length = usize::try_from(u32::from_be_bytes(
            length_bytes
                .try_into()
                .map_err(|_| SiteTrustCanonicalPayloadErrorV1::NonCanonical)?,
        ))
        .map_err(|_| SiteTrustCanonicalPayloadErrorV1::NonCanonical)?;
        if !(1..=MAXIMUM_PAYLOAD_FIELD_BYTES).contains(&length) {
            return Err(SiteTrustCanonicalPayloadErrorV1::InvalidField);
        }
        let Some(value) = canonical_bytes.get(position..position + length) else {
            return Err(SiteTrustCanonicalPayloadErrorV1::NonCanonical);
        };
        position += length;
        if !value.iter().all(|byte| (0x21..=0x7e).contains(byte)) {
            return Err(SiteTrustCanonicalPayloadErrorV1::InvalidField);
        }
        fields.push(
            String::from_utf8(value.to_vec())
                .map_err(|_| SiteTrustCanonicalPayloadErrorV1::InvalidField)?,
        );
    }
    if position != canonical_bytes.len() {
        return Err(SiteTrustCanonicalPayloadErrorV1::NonCanonical);
    }
    fields
        .try_into()
        .map_err(|_| SiteTrustCanonicalPayloadErrorV1::NonCanonical)
}

fn valid_intent_reference(value: &str) -> bool {
    value.starts_with("intent-")
        && value.len() <= MAXIMUM_INTENT_BYTES - PISTIS_INTENT_PREFIX_V1.len()
        && value
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-')
}

fn contains_prohibited_material(value: &str) -> bool {
    [
        "pistis-",
        "credential",
        "private-key",
        "public-key",
        "token",
        "secret",
        "lease",
        "provider",
        "recovery",
    ]
    .iter()
    .any(|term| value.contains(term))
}

fn digest_components<const N: usize>(domain: &[u8], components: [&[u8]; N]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update(domain);
    for component in components {
        let length = u32::try_from(component.len()).expect("all components are bounded");
        hasher.update(length.to_be_bytes());
        hasher.update(component);
    }
    hasher.finalize().into()
}

