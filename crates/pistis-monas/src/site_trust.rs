/// Exact versioned profile for the durable human-authority fact.
pub const SITE_TRUST_HUMAN_AUTHORITY_FACT_PROFILE_V1: &str =
    "mnemosyne.pistis.site-trust-human-authority-fact.v1";

const PROXENOS_PAYLOAD_PROFILE_V1: &str = "mnemosyne.proxenos.std.v1";
const PISTIS_INTENT_PREFIX_V1: &str = "mnemosyne.pistis.intent.v1:";
const FACT_ID_DOMAIN_V1: &[u8] = b"mnemosyne.pistis.site-trust-fact-id.v1\0";
const ATTESTATION_CHALLENGE_DOMAIN_V1: &[u8] =
    b"mnemosyne.pistis.site-trust-app-attest-challenge.v1\0";
const FACT_PAYLOAD_FIELDS: usize = 13;
const MAXIMUM_PAYLOAD_FIELD_BYTES: usize = 128;
const MAXIMUM_ASSERTION_BYTES: usize = 16 * 1024;
const MAXIMUM_INTENT_BYTES: usize = 192;

